#' @title Export spectra from a DynLib SQLite database to an MGF file
#'
#' @description
#' Converts spectra stored in a DynLib SQLite database into an MGF
#' file. The database is loaded as a `CompDb` object and converted
#' to a `Spectra` object. Spectra can optionally be filtered by
#' experiment identifier, MS level, and spectrum type before being
#' formatted and exported using `MsBackendMgf`..
#'
#' @param sqlite_path Character(1). Path to the DynLib SQLite
#'   database.
#'
#' @param expid Optional numeric vector specifying the experiment
#'   identifiers of the spectra to export. Multiple experiments
#'   can be selected. If NULL, spectra from all experiments
#'   are exported.
#'
#' @param ms_level  Optional numeric vector specifying the MS
#'   levels to export. If NULL, no filtering by MS level
#'   is applied.
#'
#' @param spectrum_type Optional character vector specifying
#'   the spectrum types to export. For definitions of the
#'   different spectrum types, see
#'   \code{\link{similarity_RDynLib_match}}.
#'   Multiple spectrum types can be selected.
#'   If NULL, no filtering by spectrum type is applied.
#'
#' @param output_file Character(1). Path to the output MGF file,
#'   including the file name and `.mgf` extension.
#'
#' @details
#' The function creates a temporary SQLite database containing
#' the tables required by `CompoundDb`. The database is then
#' converted into a `Spectra` object.
#'
#' Spectra can be filtered by experiment identifiers, MS levels,
#' and spectrum types. Each filtering parameter accepts multiple
#' values. If a parameter is NULL, no filtering is applied
#' for that criterion.
#'
#' The spectra are formatted for GNPS-compatible MGF export.
#' The `nodename` is used as the feature identifier, and
#' a scan identifier is generated by combining the compound
#' accession and spectrum identifier.
#'
#' Additional metadata, including compound identifiers,
#' MS levels, spectrum types, precursor scan numbers,
#' and data origins, are included in the exported spectra.
#'
#' @return
#' Invisibly returns TRUE after successful export.
#' The MGF file is written to `output_file`.
#'
#' @import Spectra
#' @import CompoundDb
#' @import MsBackendMgf
#' @import DBI
#' @import RSQLite
#'
#' @author Ahlam Mentag
#'
#' @export
sql_to_mgf <- function(sqlite_path,
                       expid = NULL,
                       ms_level  = NULL,
                       spectrum_type = NULL,
                       output_file) {
  
  
  ## GNPS helper functions
  source(
    "https://raw.githubusercontent.com/jorainer/xcms-gnps-tools/master/customFunctions.R"
  )
  
  ##  Create temporary database
  tmp_db <- tempfile(fileext = ".sqlite")
  
  # Remove temporary database when function exits
  on.exit({
    if (file.exists(tmp_db)) unlink(tmp_db)
  }, add = TRUE)
  
  # Connect to original and temporary databases
  con_src <- dbConnect(SQLite(), sqlite_path)
  con_tmp <- dbConnect(SQLite(), tmp_db)
  
  # Ensure connections are closed on error
  on.exit({
    if (dbIsValid(con_src)) dbDisconnect(con_src)
    if (dbIsValid(con_tmp)) dbDisconnect(con_tmp)
  }, add = TRUE)
  
  ##  Keep only required tables
  required_tables <- c(
    "metadata",
    "ms_compound",
    "msms_spectrum",
    "msms_spectrum_peak"
  )
  
  # Check that all required tables exist
  missing_tables <- setdiff(
    required_tables,
    dbListTables(con_src)
  )
  
  if (length(missing_tables) > 0) {
    stop(
      "Missing required tables: ",
      paste(missing_tables, collapse = ", ")
    )
  }
  
  # Copy tables with their original SQL schemas
  for (tbl in required_tables) {
    
    schema <- dbGetQuery(
      con_src,
      paste0(
        "SELECT sql FROM sqlite_master WHERE type = 'table' ",
        "AND name = ",
        as.character(dbQuoteString(con_src, tbl))
      )
    )$sql
    
    dbExecute(con_tmp, schema)
    
    # Copy table content
    data <- dbReadTable(con_src, tbl)
    
    dbAppendTable(con_tmp, tbl, data)
  }
  
  # Close connections before loading with CompoundDb
  dbDisconnect(con_src)
  dbDisconnect(con_tmp)
  
  ##  Load temporary database
  cdb <- CompDb(tmp_db)
  
  ##  Convert database to Spectra
  sps <- Spectra(cdb)
  
  # Filter by experiment ID (NULL = all experiments)
  if (!is.null(expid)) {
    sps <- sps[sps$expid %in% expid]
  }
  
  if (!is.null(ms_level )) {
    sps <- sps[sps$msLevel %in% ms_level ]
  }
  
  if (!is.null(spectrum_type)) {
    sps <- sps[sps$spectrum_type %in% spectrum_type]
  }
  
  if (length(sps) == 0) {
    stop("No spectra left after filtering")
  }
  
  ## 6. Keep variables needed for export
  sps <- selectSpectraVariables(
    sps,
    c(
      "spectrum_id",
      "compound_id",
      "compound_accession",
      "precursorMz",
      "rtime",
      "nodename",
      "dataOrigin",
      "msLevel",
      "precScanNum",
      "spectrum_type"
    )
  )
  
  ## 7. Nodename becomes GNPS feature ID
  sps$feature_id <- sps$nodename
  
  ## 8. Save metadata before formatting
  spectrum_ids <- sps$spectrum_id
  compound_ids <- sps$compound_id
  compound_accessions <- sps$compound_accession
  ms_levels <- sps$msLevel
  prec_scan_nums <- sps$precScanNum
  data_origins <- sps$dataOrigin
  spectrum_types <- sps$spectrum_type
  
  ## Format spectra for GNPS
  sps_gnps <- formatSpectraForGNPS(sps)
  
  ## Create unique scan identifiers
  sps_gnps$scan_accession <- paste0(
    compound_accessions,
    "_",
    spectrum_ids
  )
  
  ##  Additional MGF metadata
  sps_gnps$COMPOUND_ID <- compound_ids
  sps_gnps$COMPOUND_ACCESSION <- compound_accessions
  sps_gnps$MSLEVEL <- ms_levels
  sps_gnps$PRECSANNUM <- prec_scan_nums
  sps_gnps$DATAORIGIN <- data_origins
  sps_gnps$SPECTRUM_TYPE <- spectrum_types
  
  ##  MGF mapping
  mgf_mapping <- spectraVariableMapping(MsBackendMgf())
  
  # Remove acquisitionNum -> SCANS mapping
  mgf_mapping <- mgf_mapping[
    names(mgf_mapping) != "acquisitionNum"
  ]
  
  # Map character identifier to SCANS
  mgf_mapping["scan_accession"] <- "SCANS"
  
  mgf_mapping["SPECTRUM_TYPE"] <- "SPECTRUM_TYPE"
  
  ##Export MGF
  export(
    sps_gnps,
    backend = MsBackendMgf(),
    file = output_file,
    mapping = mgf_mapping
  )
  
  message(
    "MGF successfully exported: ",
    output_file,
    " (", length(sps_gnps), " spectra)"
  )
  
  invisible(TRUE)
}