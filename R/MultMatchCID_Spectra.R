
#' @title Match spectra of a compound against a DynLib spectral database
#'
#' @description
#' Calculates spectral similarity between fragmentation spectra
#' associated with a specified compound and candidate spectra
#' stored in a DynLib database. The function supports both
#' unit-resolution and high-resolution fragment matching,
#' using resolution-specific peak matching and similarity
#' scoring methods.
#'
#' @param spectra_db A `Spectra` object containing the query
#'   compound spectra and the target spectral database.
#'
#' @param compound_id Identifier of the compound whose spectra
#'   are used as queries for spectral matching.
#'
#' @inheritParams similarity_RDynLib_match
#'
#' @param spectrum_type_query Optional character(1) specifying
#'   the spectrum type to use as query spectra.
#'   Common spectrum types include:
#'
#'   - `"individual"`: An experimentally acquired fragmentation
#'     spectrum that has not been generated by combining multiple
#'     spectra. It may have undergone preprocessing, such as
#'     denoising.
#'
#'   - `"same_energy"`: A spectrum generated by combining
#'     fragmentation spectra associated with the same feature
#'     and acquired at the same collision energy.
#'
#'   - `"all_energies"`: A spectrum generated by combining
#'     `"same_energy"` spectra associated with the same feature
#'     across different collision energies.
#'
#'   - `"pseudo_MS2"`: A spectrum generated by flattening an
#'     MSn fragmentation tree, combining fragmentation information
#'     from multiple MS levels into a single spectrum.
#'
#'   Available types are determined from the spectrum-type
#'   metadata of the query spectra. If NULL and more than one
#'   type is available, the user is prompted to select a type.
#'   If only one type is available, no spectrum-type filtering
#'   is applied unless a type is explicitly specified.
#'
#' @param spectrum_type_target Optional character(1) specifying
#'   the spectrum type to use as target spectra. See
#'   `spectrum_type_query` for spectrum-type definitions.
#'   If NULL and spectrum-type metadata are available,
#'   the user is prompted to select a type.
#'   Missing spectrum-type values can also be selected
#'   by specifying `"NA"`.
#'
#' @param ms_level_query Optional numeric vector specifying
#'   the MS levels to use as query spectra. Multiple levels
#'   can be selected. Available levels are determined from
#'   the query spectra after spectrum-type and minimum
#'   fragment-count filtering.
#'   If NULL, the available level is selected automatically
#'   when only one level is present. Otherwise, the user
#'   is prompted to select one or more levels.
#'
#' @param ms_level_target Optional numeric vector specifying
#'   the MS levels to use as target spectra. Multiple levels
#'   can be selected. If NULL, the query MS levels are used
#'   when they are all available among the target spectra,
#'   or when only one target MS level is available.
#'   Otherwise, the user is prompted to select one or more
#'   target MS levels. Selected levels must exist in the
#'   target spectra.
#'
#' @param minIons Numeric(1). Minimum number of fragment peaks
#'   required in both query and target spectra before matching,
#'   and minimum number of matched peaks required for a
#'   spectral match to be retained. Defaults to 3.
#'
#' @param excludeSelf Logical(1). Whether to exclude spectra
#'   associated with the query compound from the target
#'   spectra to prevent self-matching. Defaults to TRUE.
#'
#' @details
#' Query spectra are selected from `spectra_db` using the
#' specified `compound_id` and `polarity_query`.
#' They are subsequently filtered by spectrum type,
#' minimum fragment count, and MS level.
#'
#' Target spectra are selected from the same database
#' using `polarity_target`. Only target spectra with
#' a non-missing, non-empty name that does not begin
#' with `"!"` are retained.
#' If `excludeSelf = TRUE`, spectra associated with the
#' query compound are excluded from the target set.
#'
#' Target spectra are subsequently filtered by spectrum
#' type, minimum fragment count, and MS level.
#'
#' By default, query spectra are compared with target
#' spectra of the same MS level. If the selected target
#' MS levels differ from the query MS levels, comparisons
#' are performed against all selected target MS levels,
#' allowing comparisons across different MS levels.
#'
#' For `fragments_resolution = "unit.resolution"`,
#' fragment matching uses `dynlibmatch2_map` and
#' similarity is calculated using
#' `dynlib_symmetric_dotproduct`.
#'
#' For `fragments_resolution = "high.resolution"`,
#' fragment matching uses `joinPeaksGnps` and
#' similarity is calculated using `MsCoreUtils::gnps`.
#'
#' When `requirePrecursor = TRUE`, precursor m/z
#' matching is required before spectral similarity
#' is calculated. The `ppm` and `tolerance`
#' parameters control the allowed m/z differences.
#'
#' Matches are retained only if their similarity
#' score is greater than or equal to `threshold`
#' and their number of matched peaks is greater
#' than or equal to `minIons`.
#'
#' @return
#' A `data.frame` containing the retained spectral
#' matches and associated metadata, including:
#'
#' - `query_spectrum_index`: Index of the query spectrum
#'   among the selected query spectra.
#' - `target_compound_id`: Identifier of the matched
#'   target compound.
#' - `query_msLevel_used`: MS level of the query spectrum.
#' - `target_msLevel`: MS level of the target spectrum.
#' - `query_precursorMz`: Precursor m/z of the query spectrum.
#' - `target_precursorMz`: Precursor m/z of the target spectrum.
#' - `#FragIon`: Number of peaks in the query spectrum.
#' - `ComIons`: Number of matched fragment peaks.
#' - `DotIons`: Spectral similarity score.
#' - `target_name`: Name of the matched target compound.
#' - `target_retention_time`: Retention time of the target.
#' - `query_retention_time`: Retention time of the query.
#' - `target_expid`: Target experiment identifier.
#' - `query_expid`: Query experiment identifier.
#'
#' Only columns available in the matching results
#' are included.
#'
#' If no target spectra remain after filtering, or
#' no matches satisfy the selection criteria, the
#' function returns a character message describing
#' the outcome. Invalid query selections or MS levels
#' may result in an error.
#'
#' @import BiocParallel
#' @import Spectra
#' @import MetaboAnnotation
#' @import rstudioapi
#'
#' @author Ahlam Mentag, Rebecca Dauwe, Johannes Rainer
#'
#' @export

MultMatchCID_Spectra <- function(
    spectra_db,
    compound_id,
    polarity_query,
    polarity_target,
    spectrum_type_query = NULL,
    spectrum_type_target = NULL,
    ms_level_query = NULL,
    ms_level_target = NULL,
    minIons = 3,
    fragments_resolution = c("unit.resolution", "high.resolution"),
    requirePrecursor = TRUE,
    threshold = 0.8,
    ppm = 2,
    tolerance = 0.5,
    excludeSelf = TRUE
) {
  
  fragments_resolution <- match.arg(fragments_resolution)
  
  
  # Query spectra
  
  query_meta_cols <- intersect(
    c(
      "compound_id", "polarity", "name", "spectrum_type", "spectrum.type",
      "msLevel", "precursorMz", "rtime", "expid", "retention_time"
    ),
    spectraVariables(spectra_db)
  )
  
  meta_query <- spectraData(spectra_db, query_meta_cols)
  
  query_sps <- spectra_db[
    meta_query$compound_id == compound_id &
      meta_query$polarity == polarity_query
  ]
  
  if (length(query_sps) == 0)
    stop("Compound not found with given polarity.")
  
  
  # Detect spectrum type column
  
  spectrum_col <- intersect(
    c("spectrum_type", "spectrum.type"),
    query_meta_cols
  )
  
  spectrum_col <- if (length(spectrum_col) > 0) {
    spectrum_col[1]
  } else {
    NULL
  }
  
  
  vars_keep <- c(
    "compound_id", "polarity", "msLevel", "name",
    "rtime", "precursorMz", "expid", "retention_time"
  )
  
  if (!is.null(spectrum_col))
    vars_keep <- c(spectrum_col, vars_keep)
  
  query_sps <- selectSpectraVariables(
    query_sps,
    vars_keep
  )
  
  
  # Spectrum type filter applied to all spectra of the compound,
  # regardless of MS level
  
  if (!is.null(spectrum_col)) {
    
    available_types <- unique(
      spectraData(query_sps, spectrum_col)[[1]]
    )
    
    if (is.null(spectrum_type_query) &&
        length(available_types) > 1) {
      
      spectrum_type_query <- rstudioapi::showPrompt(
        "Spectrum type selection (query)",
        paste(
          "Available types:",
          paste(available_types, collapse = ", ")
        ),
        default = available_types[1]
      )
    }
    
    if (!is.null(spectrum_type_query) &&
        spectrum_type_query %in% available_types) {
      
      query_sps <- query_sps[
        spectraData(query_sps, spectrum_col)[[1]] ==
          spectrum_type_query
      ]
    }
  }
  
  
  if (length(query_sps) == 0)
    stop("No query spectra left after spectrum_type filtering.")
  
  
  # Apply minimum number of fragment ions filter to query spectra
  
  query_peaks_list <- peaksData(query_sps)
  
  keep_idx <- vapply(
    query_peaks_list,
    nrow,
    integer(1)
  ) >= minIons
  
  query_sps <- query_sps[keep_idx]
  
  if (length(query_sps) == 0)
    stop("No query spectra left after minIons filtering.")
  
  
  # Select query MS level
  
  available_ms_query <- sort(
    unique(msLevel(query_sps))
  )
  
  if (is.null(ms_level_query)) {
    
    if (length(available_ms_query) > 1) {
      
      sel <- rstudioapi::showPrompt(
        "MS level selection (query)",
        paste0(
          "Available MS levels for this compound: ",
          paste(available_ms_query, collapse = ", "),
          "\nEnter one value, or multiple values separated by commas, e.g. 3,4"
        ),
        default = as.character(available_ms_query[1])
      )
      
      ms_level_query <- as.numeric(
        trimws(strsplit(sel, ",")[[1]])
      )
      
    } else {
      
      ms_level_query <- available_ms_query
    }
  }
  
  
  if (!all(ms_level_query %in% available_ms_query)) {
    
    stop(sprintf(
      "Invalid query MS level(s). Available MS levels for this compound: %s",
      paste(available_ms_query, collapse = ", ")
    ))
  }
  
  
  query_sps <- query_sps[
    msLevel(query_sps) %in% ms_level_query
  ]
  
  if (length(query_sps) == 0)
    stop("No query spectra left after ms_level_query filtering.")
  
  
  n_query <- length(query_sps)
  query_ms_levels <- msLevel(query_sps)
  
  message(sprintf(
    "Compound %s: %d query spectrum/spectra retained for MS level(s): %s",
    compound_id,
    n_query,
    paste(
      sort(unique(query_ms_levels)),
      collapse = ", "
    )
  ))
  
  
  # Target spectra
  
  target_meta_cols <- intersect(
    c(
      "compound_id", "polarity", "name", "spectrum_type", "spectrum.type",
      "msLevel", "precursorMz", "rtime", "expid", "retention_time"
    ),
    spectraVariables(spectra_db)
  )
  
  meta_target <- spectraData(
    spectra_db,
    target_meta_cols
  )
  
  
  # Keep target spectra with the requested polarity and a valid name
  
  target_filter <-
    meta_target$polarity == polarity_target &
    !is.na(meta_target$name) &
    meta_target$name != "" &
    !grepl("^!", meta_target$name)
  
  
  # Exclude spectra from the query compound itself to avoid
  # trivial self-matches with a score of 1
  
  if (excludeSelf &&
      "compound_id" %in% colnames(meta_target)) {
    
    target_filter <- target_filter &
      (
        is.na(meta_target$compound_id) |
          meta_target$compound_id != compound_id
      )
  }
  
  
  target_sps_all <- spectra_db[target_filter]
  
  
  vars_keep_t <- c(
    "compound_id", "polarity", "msLevel", "rtime",
    "name", "precursorMz", "expid", "retention_time"
  )
  
  if (!is.null(spectrum_col))
    vars_keep_t <- c(spectrum_col, vars_keep_t)
  
  target_sps_all <- selectSpectraVariables(
    target_sps_all,
    vars_keep_t
  )
  
  
  # Apply spectrum type filter to target spectra
  
  if (!is.null(spectrum_col)) {
    
    available_types_target <- unique(
      spectraData(target_sps_all, spectrum_col)[[1]]
    )
    
    display_types <- ifelse(
      is.na(available_types_target),
      "NA",
      available_types_target
    )
    
    if (is.null(spectrum_type_target)) {
      
      cat("\nAvailable target spectrum types:\n")
      print(display_types)
      
      spectrum_type_target <- rstudioapi::showPrompt(
        "Spectrum type selection (target)",
        "Enter one of the available spectrum types:",
        default = display_types[1]
      )
    }
    
    if (identical(spectrum_type_target, "NA"))
      spectrum_type_target <- NA
    
    target_sps_all <- target_sps_all[
      spectraData(target_sps_all, spectrum_col)[[1]] ==
        spectrum_type_target |
        (
          is.na(
            spectraData(target_sps_all, spectrum_col)[[1]]
          ) &
            is.na(spectrum_type_target)
        )
    ]
  }
  
  
  # Apply minimum number of fragment ions filter to target spectra
  
  target_sps_all <- target_sps_all[
    vapply(
      peaksData(target_sps_all),
      nrow,
      integer(1)
    ) >= minIons
  ]
  
  if (length(target_sps_all) == 0)
    return("No target spectra left after filtering.")
  
  
  # Select target MS level
  
  available_ms_target <- sort(
    unique(msLevel(target_sps_all))
  )
  
  if (is.null(ms_level_target)) {
    
    if (
      length(available_ms_target) > 1 &&
      !all(ms_level_query %in% available_ms_target)
    ) {
      
      sel <- rstudioapi::showPrompt(
        "MS level selection (target)",
        paste0(
          "Available target MS levels: ",
          paste(available_ms_target, collapse = ", "),
          "\nEnter one value, or multiple values separated by commas."
        ),
        default = as.character(available_ms_target[1])
      )
      
      ms_level_target <- as.numeric(
        trimws(strsplit(sel, ",")[[1]])
      )
      
    } else {
      
      ms_level_target <- ms_level_query
    }
  }
  
  
  if (!all(ms_level_target %in% available_ms_target)) {
    
    stop(sprintf(
      "Invalid target MS level(s). Available MS levels: %s",
      paste(available_ms_target, collapse = ", ")
    ))
  }
  
  
  target_sps_all <- target_sps_all[
    msLevel(target_sps_all) %in% ms_level_target
  ]
  
  if (length(target_sps_all) == 0)
    return("No target spectra left after ms_level_target filtering.")
  
  
  target_ms_levels_all <- msLevel(target_sps_all)
  
  ms_target_fixed <- !setequal(
    ms_level_target,
    ms_level_query
  )
  
  
  # Spectral matching
  
  all_results <- list()
  
  for (i in seq_len(n_query)) {
    
    q_sp <- query_sps[i]
    q_ms <- query_ms_levels[i]
    
    
    # If target MS levels were explicitly set to different levels,
    # use all selected target spectra. Otherwise, compare spectra
    # belonging to the same MS level.
    
    if (ms_target_fixed) {
      
      target_sps <- target_sps_all
      
    } else {
      
      target_sps <- target_sps_all[
        target_ms_levels_all == q_ms
      ]
    }
    
    
    if (length(target_sps) == 0) {
      
      message(sprintf(
        "  - MS%d: no target spectra available; spectrum skipped.",
        q_ms
      ))
      
      next
    }
    
    
    # Unit-resolution spectral matching
    
    if (fragments_resolution == "unit.resolution") {
      
      param <- MetaboAnnotation::CompareSpectraParam(
        ppm = ppm,
        tolerance = tolerance,
        threshold = threshold,
        requirePrecursor = requirePrecursor,
        MAPFUN = dynlibmatch2_map,
        FUN = dynlib_symmetric_dotproduct,
        matchedPeaksCount = TRUE,
        fragments_method = fragments_resolution
      )
      
      matches <- MetaboAnnotation::matchSpectra(
        query = q_sp,
        target = target_sps,
        param = param
      )
      
      
      # High-resolution spectral matching
      
    } else {
      
      param <- CompareSpectraParam(
        ppm = ppm,
        tolerance = tolerance,
        MAPFUN = joinPeaksGnps,
        FUN = MsCoreUtils::gnps,
        threshold = threshold,
        requirePrecursor = requirePrecursor,
        matchedPeaksCount = TRUE
      )
      
      matches <- matchSpectra(
        query = q_sp,
        target = target_sps,
        param = param
      )
    }
    
    
    # Extract and filter matching results
    
    df_i <- as.data.frame(
      MetaboAnnotation::matchedData(matches)
    )
    
    if (nrow(df_i) == 0)
      next
    
    
    # Retain matches above the similarity threshold
    
    df_i <- df_i[
      !is.na(df_i$score) &
        df_i$score >= threshold,
      ,
      drop = FALSE
    ]
    
    if (nrow(df_i) == 0)
      next
    
    
    # Retain matches with the required minimum number of matched ions
    
    df_i <- df_i[
      df_i$matched_peaks_count >= minIons,
      ,
      drop = FALSE
    ]
    
    if (nrow(df_i) == 0)
      next
    
    
    # Add query and matching information
    
    df_i$query_spectrum_index <- i
    df_i$query_msLevel_used <- q_ms
    df_i$`#FragIon` <- nrow(
      peaksData(q_sp)[[1]]
    )
    df_i$ComIons <- df_i$matched_peaks_count
    df_i$DotIons <- df_i$score
    
    all_results[[length(all_results) + 1]] <- df_i
  }
  
  
  if (length(all_results) == 0)
    return("No matches found for any MS level of this compound.")
  
  
  # Combine matching results
  
  df <- do.call(
    rbind,
    all_results
  )
  
  
  # Rename and add output variables
  
  if ("target_compound_id" %in% colnames(df))
    df$COMPID <- df$target_compound_id
  
  if ("precursorMz" %in% colnames(df))
    df$query_precursorMz <- df$precursorMz
  
  if ("retention_time" %in% colnames(df))
    df$query_retention_time <- df$retention_time
  
  if ("expid" %in% colnames(df))
    df$query_expid <- df$expid
  
  if ("msLevel" %in% colnames(df))
    df$query_msLevel <- df$msLevel
  
  
  # Define output column order
  
  cols_order <- c(
    "query_spectrum_index",
    "target_compound_id",
    "query_msLevel_used",
    "target_msLevel",
    "query_precursorMz",
    "target_precursorMz",
    "#FragIon",
    "ComIons",
    "DotIons",
    "target_name",
    "target_retention_time",
    "query_retention_time",
    "target_expid",
    "query_expid"
  )
  
  cols_order <- cols_order[
    cols_order %in% colnames(df)
  ]
  
  df <- df[
    ,
    cols_order,
    drop = FALSE
  ]
  
  
  # Round similarity scores
  
  if ("DotIons" %in% colnames(df))
    df$DotIons <- round(df$DotIons, 2)
  
  
  # Round precursor m/z values for unit-resolution matching
  
  if (fragments_resolution == "unit.resolution") {
    
    if ("query_precursorMz" %in% colnames(df))
      df$query_precursorMz <- round(
        df$query_precursorMz,
        2
      )
    
    if ("target_precursorMz" %in% colnames(df))
      df$target_precursorMz <- round(
        df$target_precursorMz,
        2
      )
  }
  
  
  rownames(df) <- NULL
  
  return(df)
}